'use strict';
// Wave 4 (NAV-01): real URL boot translation.
//
// The storefront renders from location.hash. A shopper who lands on a
// real URL (served by the framework catch all route in
// app/collections/[...slug]/route.ts) arrives with a pathname and no
// hash. This script runs before every other storefront script and,
// only when the URL carries no hash, translates a known real path
// into the equivalent hash route so the existing render dispatch
// boots straight into the requested screen. Any URL that already has
// a hash is left untouched, so every existing hash link, bookmark and
// in-app navigation behaves exactly as before. Unknown paths are not
// mapped: the server answers them with a 404 before this script ever
// runs, and this script never invents a destination for them.
//
// The maps live in public/real-routes-data.js, generated by
// scripts/build-real-routes.cjs from the menu source
// (data/reference-navigation.json) and the catalog collection data
// (data/collections.json): the same sources the catalog generators
// use, so there is one source of truth per route. Alias paths
// (legacy spellings, the retired Pants wording) resolve to the
// canonical path's hash, so entering through an alias renders the
// canonical destination.
const routePaths=(typeof realRoutePaths!=='undefined')?realRoutePaths:{};
const routeAliases=(typeof realRouteAliases!=='undefined')?realRouteAliases:{};
function normalizeRealPath(pathname){
  if(!pathname)return null;
  let key=String(pathname);
  try{key=decodeURIComponent(key)}catch(e){/* keep the raw path */}
  return key.toLowerCase().replace(/\/+$/,'');
}
function canonicalRealPath(pathname){
  const key=normalizeRealPath(pathname);
  if(!key)return null;
  if(routePaths[key])return key;
  return routeAliases[key]||null;
}
function hashForRealPath(pathname){
  const canonical=canonicalRealPath(pathname);
  return canonical?routePaths[canonical]:null;
}
function applyRealRoute(loc){
  const target=loc||(typeof location!=='undefined'?location:null);
  if(!target||target.hash)return null;
  const hash=hashForRealPath(target.pathname||'');
  if(hash)target.hash=hash;
  return hash;
}
if(typeof window!=='undefined'&&typeof location!=='undefined')applyRealRoute(location);
