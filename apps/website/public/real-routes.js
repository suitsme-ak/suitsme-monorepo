'use strict';
// Wave 4 (NAV-01): real URL boot translation and link translation.
//
// The storefront renders from location.hash. A shopper who lands on a
// real URL (served by the framework routes under app/, which serve the
// storefront document for every migrated path) arrives with a pathname
// and no hash. This script runs before every other storefront script
// and, only when the URL carries no hash, translates a known real path
// into the equivalent hash route so the existing render dispatch boots
// straight into the requested screen. Any URL that already has a hash
// is left untouched, so every existing hash link, bookmark and in-app
// navigation behaves exactly as before. Unknown paths are not mapped:
// the server answers them with a 404 before this script ever runs, and
// this script never invents a destination for them.
//
// The maps live in public/real-routes-data.js, generated by
// scripts/build-real-routes.cjs from the menu source
// (data/reference-navigation.json), the catalog collection data
// (data/collections.json) and the product catalog
// (data/catalog.json): the same sources the catalog generators use, so
// there is one source of truth per route. Alias paths (legacy
// spellings, the retired Pants wording) resolve to the canonical
// path's hash, so entering through an alias renders the canonical
// destination.
//
// Stage 3a covers every route family: collections, the single segment
// pages, the fabrics and studio kind listings, product detail
// (validated against the generated catalog id ranges, so an unknown id
// maps to nothing here and 404s on the server), and order detail.
// Order ids are matched case sensitively and are not validated: they
// live in the shopper's browser storage or in server order records,
// so any single segment id boots into the order route and the client
// renders its own not found state for an unknown id, exactly as the
// hash route does today.
//
// realUrlForHash is the reverse translation, used by navigation.js
// and the rendered page templates so internal links point at real
// URLs. A hash with no real equivalent is returned unchanged.
const routePaths=(typeof realRoutePaths!=='undefined')?realRoutePaths:{};
const routeAliases=(typeof realRouteAliases!=='undefined')?realRouteAliases:{};
const routeReverse=(typeof realRouteReverse!=='undefined')?realRouteReverse:{};
const routePages=(typeof realRoutePages!=='undefined')?realRoutePages:{};
const routeFamilies=(typeof realRouteFamilies!=='undefined')?realRouteFamilies:{};
function normalizeRealPath(pathname){
  if(!pathname)return null;
  let key=String(pathname);
  try{key=decodeURIComponent(key)}catch(e){/* keep the raw path */}
  return key.toLowerCase().replace(/\/+$/,'');
}
function canonicalRealPath(pathname){
  const key=normalizeRealPath(pathname);
  if(!key)return null;
  if(routePaths[key])return key;
  return routeAliases[key]||null;
}
function validProductId(id){
  const ranges=(routeFamilies.product&&routeFamilies.product.idRanges)||[];
  return ranges.some(([lo,hi])=>id>=lo&&id<=hi);
}
function familyHash(key,raw){
  const seg=key.split('/').filter(Boolean);
  if(seg.length!==2)return null;
  if(seg[0]==='fabrics'&&routeFamilies.fabrics&&routeFamilies.fabrics.kinds.includes(seg[1]))return '#fabrics/'+seg[1];
  if(seg[0]==='studio'&&routeFamilies.studio&&routeFamilies.studio.kinds.includes(seg[1]))return '#studio/'+seg[1];
  if(seg[0]==='product'&&/^\d+$/.test(seg[1])){
    const id=parseInt(seg[1],10);
    return validProductId(id)?'#product/'+id:null;
  }
  if(seg[0]==='orders'){
    // Case matters for order ids, so this family matches on the raw
    // (decoded, slash trimmed) segments, not the lowercased key.
    const rawSeg=raw.split('/').filter(Boolean);
    if(rawSeg.length===2&&rawSeg[1])return '#order/'+rawSeg[1];
  }
  return null;
}
function hashForRealPath(pathname){
  if(!pathname)return null;
  let raw=String(pathname);
  try{raw=decodeURIComponent(raw)}catch(e){/* keep the raw path */}
  raw=raw.replace(/\/+$/,'');
  const key=raw.toLowerCase();
  if(routePaths[key])return routePaths[key];
  if(routeAliases[key])return routePaths[routeAliases[key]];
  if(routePages[key])return routePages[key];
  return familyHash(key,raw);
}
function realUrlForHash(hash){
  if(!hash||hash==='#'||hash==='#home')return '/';
  if(hash==='#story')return '/#craft';
  if(routeReverse[hash])return routeReverse[hash];
  let m=/^#product\/(\d+)$/.exec(hash);
  if(m)return '/product/'+m[1];
  m=/^#order\/(.+)$/.exec(hash);
  if(m)return '/orders/'+m[1];
  m=/^#fabrics\/([a-z]+)$/.exec(hash);
  if(m&&routeFamilies.fabrics&&routeFamilies.fabrics.kinds.includes(m[1]))return '/fabrics/'+m[1];
  m=/^#studio\/([a-z]+)$/.exec(hash);
  if(m&&routeFamilies.studio&&routeFamilies.studio.kinds.includes(m[1]))return '/studio/'+m[1];
  return hash;
}
function applyRealRoute(loc){
  const target=loc||(typeof location!=='undefined'?location:null);
  if(!target||target.hash)return null;
  const hash=hashForRealPath(target.pathname||'');
  if(hash)target.hash=hash;
  return hash;
}
if(typeof window!=='undefined'&&typeof location!=='undefined')applyRealRoute(location);
