// Builds public/measurement-schema.js from lib/measurement-schema.js.
//
// The measurement schema is one file with two runtimes: the server
// validators read the module in lib/ directly, and the browser
// studio loads a classic script. The transform is deliberately
// mechanical: strip the leading module declaration keyword from
// each top level declaration, so the data and the functions become
// the browser globals the other public scripts already rely on.
// The schema source is written to survive exactly this transform
// (top level declarations only, no dependencies), and this script
// refuses to emit a copy that still carries module syntax.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'lib', 'measurement-schema.js'), 'utf8');
const body = source.replace(/^export (?=(?:const|let|var|function|class) )/gm, '');
if (/\bexport\b/.test(body)) throw new Error('measurement-schema: a module declaration survived the transform; the schema source must declare top level consts and functions only.');
if (/\bimport\b/.test(body)) throw new Error('measurement-schema: the schema must stay dependency free.');
const banner = '/* Generated by scripts/build-measurement-schema.cjs from lib/measurement-schema.js. Do not edit this file directly. */\n';
fs.writeFileSync(path.join(root, 'public', 'measurement-schema.js'), banner + body);
console.log('Built public/measurement-schema.js from lib/measurement-schema.js');
